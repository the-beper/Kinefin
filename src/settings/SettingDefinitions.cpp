const QList<SettingDefinition> &settingDefinitions()
{
    static const QList<SettingDefinition> definitions = buildDefinitions();
    return definitions;
}

const SettingDefinition *findSetting(const QString &section, const QString &key)
{
    for (const SettingDefinition &definition : settingDefinitions()) {
        if (definition.section == section && definition.key == key)
            return &definition;
    }
    return nullptr;
}

QVariant validatedSettingValue(const SettingDefinition &definition, const QVariant &value)
{
    QVariant converted;
    switch (definition.type) {
    case T::Bool:
        if (value.metaType().id() == QMetaType::Bool)
            converted = value;
        break;
    case T::Int:
        if (value.metaType().id() == QMetaType::Int)
            converted = value;
        else if (value.canConvert<double>() && value.metaType().id() != QMetaType::QString
                 && value.metaType().id() != QMetaType::Bool) {
            // QML hands numbers over as doubles
            const double number = value.toDouble();
            if (std::isfinite(number) && number >= std::numeric_limits<int>::min()
                && number <= std::numeric_limits<int>::max() && number == static_cast<int>(number))
                converted = static_cast<int>(number);
        }
        break;
    case T::Double:
        if (value.metaType().id() == QMetaType::Double || value.metaType().id() == QMetaType::Int)
            converted = value.toDouble();
        if (converted.isValid()
            && (!std::isfinite(converted.toDouble()) || converted.toDouble() < definition.min
                || converted.toDouble() > definition.max))
            converted = {};
        break;
    case T::String:
        // Only a multiline setting may carry line breaks; the others end up in one mpv property or one config line
        if (value.metaType().id() == QMetaType::QString
            && (definition.multiline
                || !(value.toString().contains(QLatin1Char('\n'))
                     || value.toString().contains(QLatin1Char('\r')))))
            converted = value;
        break;
    }
    if (!converted.isValid() || definition.options.isEmpty())
        return converted;
    for (const SettingDefinition::Option &option : definition.options) {
        if (sameValue(option.value, converted))
            return converted;
    }
    return {};
}
